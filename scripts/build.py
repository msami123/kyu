#!/usr/bin/env python3
"""Build the agent files for both providers from a single source of truth.

Reads:
  agents/shared-foundation.md, agents/<role>.md, config/agents.yaml, config/pipeline.yaml
Writes (all generated; do not edit by hand, edit the sources and rebuild):
  CLAUDE.md                     shared foundation for Claude Code (loaded by every session/subagent)
  AGENTS.md                     shared foundation for Codex CLI (loaded automatically by codex)
  .claude/agents/<id>.md        Claude Code subagents (provider: anthropic)
  codex/<id>.md                 role prompts for Codex CLI (provider: openai)
  kickoffs/<stage>-<step>-<n>-<agent>.md   one kickoff message per pipeline run
No API keys: Claude Code uses your Claude login, Codex CLI uses your ChatGPT login.

Validates:
  - every role file exists, providers are known, pipeline agents exist
  - independence rules (must_differ = error, should_differ = warning)
  - every work/ input is produced earlier in the pipeline or is a known human file

Usage:  python3 scripts/build.py           (from the project root)
        python3 scripts/build.py --check   (validate only, write nothing)
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

try:
    import yaml  # PyYAML
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required:  pip install pyyaml")

ROOT = Path(__file__).resolve().parent.parent
PROVIDERS = {"anthropic", "openai"}
OPENAI_REASONING_EFFORTS = {"none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra"}
# work/ files the human creates (not produced by any agent run)
HUMAN_FILES = {"work/00-client-notes.md", "work/08-script-approved.md", "work/decision-log.md",
               "work/12-qc-log.md"}
GENERATED_NOTE = ("<!-- GENERATED by scripts/build.py from agents/ and config/. "
                  "Edit the sources, then rebuild. -->\n")


class BuildError(Exception):
    pass


def load_yaml(rel: str) -> dict:
    path = ROOT / rel
    if not path.exists():
        raise BuildError(f"missing {rel}")
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def read(rel: str) -> str:
    path = ROOT / rel
    if not path.exists():
        raise BuildError(f"missing {rel}")
    return path.read_text(encoding="utf-8").strip() + "\n"


def params_block(params: dict | None) -> str:
    if not params:
        return ""
    lines = "\n".join(f"{k}: {v}" for k, v in params.items())
    return f"\n## Your instance parameters (fixed for this agent)\n{lines}\n"


# --------------------------------------------------------------------------- validation
def validate(agents_cfg: dict, pipeline: dict) -> list[str]:
    errors, warnings = [], []
    agents = agents_cfg.get("agents", {})
    if not agents:
        raise BuildError("config/agents.yaml has no agents")

    for aid, a in agents.items():
        if a.get("provider") not in PROVIDERS:
            errors.append(f"{aid}: provider must be one of {sorted(PROVIDERS)}")
        if not (ROOT / a.get("role_file", "")).exists():
            errors.append(f"{aid}: role_file not found: {a.get('role_file')}")
        if not a.get("description"):
            errors.append(f"{aid}: description is required (Claude Code uses it to delegate)")
        effort = a.get("model_reasoning_effort")
        if effort is not None:
            if a.get("provider") != "openai":
                errors.append(f"{aid}: model_reasoning_effort is only supported for openai agents")
            elif not isinstance(effort, str) or effort not in OPENAI_REASONING_EFFORTS:
                errors.append(f"{aid}: invalid model_reasoning_effort: {effort!r}")

    rules = agents_cfg.get("rules", {})
    for level, bucket in (("must_differ", errors), ("should_differ", warnings)):
        for pair in rules.get(level, []):
            x, y = pair
            if x not in agents or y not in agents:
                errors.append(f"rules.{level}: unknown agent in {pair}")
                continue
            if agents[x]["provider"] == agents[y]["provider"]:
                bucket.append(f"independence rule {level}: {x} and {y} are both on "
                              f"'{agents[x]['provider']}'")

    produced: set[str] = set(HUMAN_FILES)
    outputs_seen: dict[str, str] = {}
    for stage in pipeline.get("stages", []):
        sid = stage["id"]
        for si, step in enumerate(stage.get("steps", []), start=1):
            step_outputs = []
            for run in step:
                aid = run.get("agent")
                if aid not in agents:
                    errors.append(f"stage {sid} step {si}: unknown agent '{aid}'")
                for inp in run.get("inputs", []):
                    if inp.startswith("work/") and not inp.endswith("/") and inp not in produced:
                        warnings.append(f"stage {sid} step {si} ({aid}): input {inp} is not "
                                        "produced by an earlier step or listed as a human file")
                out = str(run.get("output", ""))
                if out.startswith("work/"):
                    if out in outputs_seen:
                        errors.append(f"stage {sid}: output {out} also written by "
                                      f"{outputs_seen[out]}")
                    outputs_seen[out] = f"stage {sid} step {si} ({aid})"
                    step_outputs.append(out)
            # outputs of a parallel step become available only after the whole step
            produced.update(step_outputs)

    for w in warnings:
        print(f"WARNING  {w}")
    if errors:
        for e in errors:
            print(f"ERROR    {e}")
        raise BuildError(f"{len(errors)} error(s); nothing written")
    return warnings


# --------------------------------------------------------------------------- writers
def write(rel: str, text: str) -> None:
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def build_foundations(foundation: str) -> None:
    claude_md = (
        GENERATED_NOTE
        + "# Project memory for Claude Code\n\n"
        "If you are the MAIN session, you are the orchestrator: follow PIPELINE.md, start runs\n"
        "with the kickoff files in kickoffs/, run the runs of one step in parallel as subagents,\n"
        "and stop at every gate and client checkpoint for the human.\n"
        "If you were started as a SUBAGENT, ignore orchestration: do only your role.\n\n"
        "Agents with provider openai run in Codex CLI, not as your subagents. To run one, use\n"
        "Bash:  python3 scripts/run.py --run <kickoff file name>   (several can run in the\n"
        "background in parallel). Each agent writes its own output file.\n\n---\n\n"
        + foundation
    )
    agents_md = (
        GENERATED_NOTE
        + "# Shared foundation for Codex-side agents\n\n"
        "Codex loads this file automatically. Your role prompt (codex/<agent id>.md) and the\n"
        "KICKOFF message arrive in the task prompt. Write your output to the path the kickoff\n"
        "names, using your file tools.\n\n---\n\n"
        + foundation
    )
    write("CLAUDE.md", claude_md)
    write("AGENTS.md", agents_md)


def build_agents(agents_cfg: dict, foundation: str) -> tuple[list[str], list[str]]:
    defaults = agents_cfg.get("defaults", {})
    base_tools = defaults.get("anthropic_tools", ["Read", "Write", "Edit", "Glob", "Grep"])
    claude_dir, codex_dir = ROOT / ".claude" / "agents", ROOT / "codex"
    legacy = ROOT / "openai"  # older builds wrote API system prompts here
    if legacy.exists():
        shutil.rmtree(legacy)
    for d in (claude_dir, codex_dir):
        if d.exists():
            shutil.rmtree(d)
        d.mkdir(parents=True)

    made_claude, made_openai = [], []
    for aid, a in agents_cfg["agents"].items():
        role = read(a["role_file"])
        extra = params_block(a.get("params"))
        if a["provider"] == "anthropic":
            tools = list(dict.fromkeys(base_tools + a.get("extra_tools", [])))
            front = (
                "---\n"
                f"name: {aid}\n"
                f"description: {json.dumps(' '.join(a['description'].split()), ensure_ascii=False)}\n"
                f"tools: {', '.join(tools)}\n"
                f"model: {a.get('model', 'inherit')}\n"
                "---\n"
            )
            body = (
                GENERATED_NOTE
                + "The shared foundation is in CLAUDE.md (loaded automatically). Follow it, then the "
                "role below. Your task arrives as a KICKOFF message.\n"
                + extra + "\n" + role
            )
            write(f".claude/agents/{aid}.md", front + body)
            made_claude.append(aid)
        else:
            body = (
                GENERATED_NOTE
                + f"# You are the agent '{aid}'\n\n"
                "The shared foundation is in AGENTS.md (loaded automatically). Follow it, then the "
                "role below.\n\n"
                "## How to work in this run\n"
                "- Read every input file listed in the KICKOFF with your file tools.\n"
                "- Write your result to the output path named in the KICKOFF. Create or overwrite "
                "only that file; the shared logs (work/decision-log.md, and work/12-qc-log.md for "
                "dop) are append-only.\n"
                "- Do not edit any other file, do not run builds, do not use git.\n"
                "- Your final message: one line naming the file you wrote, then the HANDOFF block.\n"
                + extra + "\n---\n\n" + role
            )
            write(f"codex/{aid}.md", body)
            made_openai.append(aid)
    return made_claude, made_openai


def build_kickoffs(agents_cfg: dict, pipeline: dict) -> int:
    kdir = ROOT / "kickoffs"
    if kdir.exists():
        shutil.rmtree(kdir)
    kdir.mkdir()
    agents = agents_cfg["agents"]
    count = 0
    index = ["# KICKOFF INDEX", "",
             "| File | Stage | Step | Parallel with | Agent | Provider | Output |",
             "|---|---|---|---|---|---|---|"]
    for stage in pipeline["stages"]:
        sid, sname = stage["id"], stage["name"]
        for si, step in enumerate(stage["steps"], start=1):
            for ri, run in enumerate(step, start=1):
                aid = run["agent"]
                a = agents[aid]
                params = {**(a.get("params") or {}), **(run.get("params") or {})}
                role_id = Path(a["role_file"]).stem
                inputs = "\n".join(f"  - {i}" for i in run.get("inputs", [])) or "  - (none)"
                text = (
                    "KICKOFF\n"
                    f"agent: {aid}\n"
                    f"role: {role_id}\n"
                    f"stage: {sid} — {sname}\n"
                    f"mode: {run.get('mode', '-')}\n"
                    f"params: {'; '.join(f'{k}={v}' for k, v in params.items()) or '-'}\n"
                    f"inputs:\n{inputs}\n"
                    f"output: {run.get('output', '-')}\n"
                    "rules: Read the shared foundation and your role file. Write only the output "
                    "named above. End with the HANDOFF block.\n"
                )
                if stage.get("gate"):
                    text += f"gate after this stage: {stage['gate']}\n"
                if stage.get("checkpoint"):
                    text += f"client checkpoint after this stage: {stage['checkpoint']}\n"
                name = f"{sid}-{si}-{ri}-{aid}.md"
                write(f"kickoffs/{name}", text)
                parallel = len(step) - 1
                index.append(f"| {name} | {sid} {sname} | {si} | {parallel or '-'} | {aid} | "
                             f"{a['provider']} | {run.get('output', '-')} |")
                count += 1
    write("kickoffs/INDEX.md", "\n".join(index) + "\n")
    return count


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate only")
    args = ap.parse_args()
    try:
        agents_cfg = load_yaml("config/agents.yaml")
        pipeline = load_yaml("config/pipeline.yaml")
        foundation = read("agents/shared-foundation.md")
        warnings = validate(agents_cfg, pipeline)
        if args.check:
            print(f"OK  validation passed ({len(warnings)} warning(s))")
            return 0
        build_foundations(foundation)
        made_claude, made_openai = build_agents(agents_cfg, foundation)
        n = build_kickoffs(agents_cfg, pipeline)
    except BuildError as exc:
        print(f"BUILD FAILED  {exc}")
        return 1
    print(f"OK  Claude Code subagents ({len(made_claude)}): {', '.join(made_claude)}")
    print(f"OK  Codex role prompts ({len(made_openai)}): {', '.join(made_openai)}")
    print(f"OK  kickoffs: {n}  (see kickoffs/INDEX.md)")
    print(f"OK  CLAUDE.md and AGENTS.md written; {len(warnings)} warning(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
